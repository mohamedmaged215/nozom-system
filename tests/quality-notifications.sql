begin;
do $$
declare
  admin_password text;
  test_password text:=gen_random_uuid()::text;
  team_a text:='qa_notice_'||gen_random_uuid()::text;
  team_b text:='qa_notice_'||gen_random_uuid()::text;
  supervisor_a text:='qa_notice_'||gen_random_uuid()::text;
  client_a text:='qa_notice_'||gen_random_uuid()::text;
  token text;
  doc jsonb;
  review_id uuid;
  denied boolean;
begin
  select password into strict admin_password from public.credentials where role='admin' limit 1;
  insert into public.teams(id,name) values(team_a,'Notification A'),(team_b,'Notification B');
  insert into public.employees(id,name,team_id,role,is_active) values(supervisor_a,'Notification supervisor',team_a,'مشرف',true);
  insert into public.clients(id,name,team_id) values(client_a,'Notification client',team_a);
  insert into public.credentials(role,team_id,password) values('supervisor',team_a,test_password);
  perform public.quality_api('admin',null,admin_password,'set_password',jsonb_build_object('password',test_password));
  assert not has_table_privilege('anon','public.quality_reads','SELECT'),'read receipts exposed';
  assert not has_table_privilege('anon','app.quality_portal_links','SELECT'),'portal tokens exposed';
  doc:=public.quality_api('supervisor',team_a,test_password,'portal_links');
  select value->>'token' into token from jsonb_array_elements(doc->'supervisors') where value->>'employee_id'=supervisor_a;
  assert length(token)=64,'missing portal link';
  denied:=false;
  begin perform public.quality_api('quality_link',team_b,token,'list'); exception when insufficient_privilege then denied:=true; end;
  assert denied,'portal crossed teams';
  denied:=false;
  begin perform public.quality_api('quality_link',team_a,'invalid','list'); exception when insufficient_privilege then denied:=true; end;
  assert denied,'invalid token accepted';
  denied:=false;
  begin perform public.quality_api('quality_link',team_a,token,'portal_links'); exception when insufficient_privilege then denied:=true; end;
  assert denied,'portal can mint tokens';
  denied:=false;
  begin perform public.quality_api('supervisor',team_a,test_password,'save_contact',jsonb_build_object('team_id',team_a,'phone','201000000000'));
    exception when insufficient_privilege then denied:=true; end;
  assert denied,'supervisor changed contacts';
  perform public.quality_api('quality',null,test_password,'save_contact',jsonb_build_object('team_id',team_a,'phone','+20 100-000-0000'));
  assert exists(select 1 from app.quality_contacts where team_id=team_a and phone='201000000000'),'phone normalization failed';
  doc:=public.quality_api('quality',null,test_password,'create',jsonb_build_object('team_id',team_a));
  review_id:=(doc->>'id')::uuid;
  doc:=public.quality_api('quality_link',team_a,token,'notifications');
  assert (doc->>'unread_count')::int=0,'draft generated notification';
  denied:=false;
  begin perform public.quality_api('quality_link',team_a,token,'get',jsonb_build_object('review_id',review_id));
    exception when insufficient_privilege then denied:=true; end;
  assert denied,'portal read draft';
  doc:=public.quality_api('quality',null,test_password,'get',jsonb_build_object('review_id',review_id));
  perform public.quality_api('quality',null,test_password,'publish',jsonb_build_object('review_id',review_id,'updated_at',doc->>'updated_at','items',
    jsonb_build_array(jsonb_build_object('client_id',client_a,'category','البنوك','observation','Notification test'))));
  doc:=public.quality_api('quality_link',team_a,token,'notifications');
  assert (doc->>'unread_count')::int=1,'new review not notified';
  doc:=public.quality_api('quality_link',team_a,token,'get',jsonb_build_object('review_id',review_id));
  assert (doc->>'notification_revision')::int=1,'publish revision failed';
  perform public.quality_api('quality_link',team_a,token,'mark_seen',jsonb_build_object('review_id',review_id,'revision',doc->>'notification_revision'));
  doc:=public.quality_api('supervisor',team_a,test_password,'notifications');
  assert (doc->>'unread_count')::int=0,'read not synchronized across portals';
  doc:=public.quality_api('quality',null,test_password,'get',jsonb_build_object('review_id',review_id));
  assert (doc->>'seen_revision')::int=1,'reviewer cannot see read receipt';
  assert doc->'items'->0->>'status'='open','viewing processed finding';
  perform public.quality_api('quality_link',team_a,token,'respond',jsonb_build_object('review_id',review_id,'finding_id',doc->'items'->0->>'id','updated_at',doc->'items'->0->>'updated_at','reply','Portal reply'));
  doc:=public.quality_api('quality',null,test_password,'get',jsonb_build_object('review_id',review_id));
  assert doc->'items'->0->>'status'='resolved','portal reply failed';
  assert (doc->>'notification_revision')::int=1,'reply triggered new notification';
  doc:=jsonb_set(doc||jsonb_build_object('review_id',review_id),'{items,0,details}','"Changed details"'::jsonb);
  perform public.quality_api('quality',null,test_password,'edit_review',doc);
  doc:=public.quality_api('quality_link',team_a,token,'notifications');
  assert (doc->>'unread_count')::int=1,'edited review not notified';
  perform public.quality_api('quality_link',team_a,token,'mark_seen',jsonb_build_object('review_id',review_id,'revision',1));
  doc:=public.quality_api('quality_link',team_a,token,'notifications');
  assert (doc->>'unread_count')::int=1,'old read cleared newer revision';
  denied:=false;
  begin perform public.quality_api('quality_link',team_a,token,'mark_seen',jsonb_build_object('review_id',review_id,'revision',999));
    exception when others then denied:=true; end;
  assert denied,'future revision marked read';
  perform public.quality_api('quality_link',team_a,token,'mark_seen',jsonb_build_object('review_id',review_id,'revision',2));
  doc:=public.quality_api('quality_link',team_a,token,'notifications');
  assert (doc->>'unread_count')::int=0,'new revision not marked read';
  denied:=false;
  begin perform public.quality_api('quality_link',team_a,token,'delete_finding',jsonb_build_object('review_id',review_id));
    exception when insufficient_privilege then denied:=true; end;
  assert denied,'portal can delete findings';
  update public.employees set is_active=false where id=supervisor_a;
  denied:=false;
  begin perform public.quality_api('quality_link',team_a,token,'notifications'); exception when insufficient_privilege then denied:=true; end;
  assert denied,'inactive supervisor still has access';
end;
$$;
rollback;
select 'Notifications, receipts, portal scope and replies passed' as result;

-- Runs against the deployed schema; every test record is rolled back.
begin;
do $$
declare
  admin_password text;
  test_password text := gen_random_uuid()::text;
  team_a text := 'quality_test_' || gen_random_uuid()::text;
  team_b text := 'quality_test_' || gen_random_uuid()::text;
  client_a text := 'quality_test_' || gen_random_uuid()::text;
  client_b text := 'quality_test_' || gen_random_uuid()::text;
  review_id uuid;
  doc jsonb;
  item jsonb;
  bad_items jsonb;
  good_items jsonb;
  denied boolean;
begin
  select password into strict admin_password from public.credentials where role='admin' limit 1;
  insert into public.teams(id,name) values(team_a,'Quality test A'),(team_b,'Quality test B');
  insert into public.clients(id,name,team_id) values(client_a,'Test client A',team_a),(client_b,'Test client B',team_b);
  insert into public.credentials(role,team_id,password) values('supervisor',team_a,test_password),('supervisor',team_b,test_password);
  perform public.quality_api('admin',null,admin_password,'set_password',jsonb_build_object('password',test_password));
  assert not has_table_privilege('anon','public.quality_reviews','SELECT'), 'anonymous table access';
  assert not has_table_privilege('anon','public.quality_findings','UPDATE'), 'anonymous table writes';
  assert has_function_privilege('anon','public.quality_api(text,text,text,text,jsonb)','EXECUTE'), 'RPC unavailable';
  denied := false;
  begin perform public.quality_api('quality',null,'invalid','list'); exception when others then denied:=true; end;
  assert denied, 'bad password allowed';
  denied := false;
  begin perform public.quality_api('employee',team_a,null,'list'); exception when insufficient_privilege then denied:=true; end;
  assert denied, 'employee allowed';

  doc := public.quality_api('quality',null,test_password,'create',jsonb_build_object('team_id',team_a));
  review_id := (doc->>'id')::uuid;
  doc := public.quality_api('quality',null,test_password,'get',jsonb_build_object('review_id',review_id));
  denied:=false;
  begin perform public.quality_api('supervisor',team_a,test_password,'get',jsonb_build_object('review_id',review_id));
    exception when insufficient_privilege then denied:=true; end;
  assert denied, 'draft visible to supervisor';
  good_items:=jsonb_build_array(jsonb_build_object('client_id',client_a,'category','البنوك','observation','رصيد البنك غير مطابق','details','Test detail'));
  bad_items:=jsonb_build_array(jsonb_build_object('client_id',client_b,'category','البنوك','observation','wrong client'));
  denied:=false;
  begin perform public.quality_api('quality',null,test_password,'publish',jsonb_build_object('review_id',review_id,'updated_at',doc->>'updated_at','items',bad_items));
    exception when others then denied:=true; end;
  assert denied, 'cross-team client accepted';
  perform public.quality_api('quality',null,test_password,'save',jsonb_build_object('review_id',review_id,'updated_at',doc->>'updated_at','items',good_items));
  denied:=false;
  begin perform public.quality_api('quality',null,test_password,'publish',jsonb_build_object('review_id',review_id,'updated_at',doc->>'updated_at','items',good_items));
    exception when others then denied:=true; end;
  assert denied, 'stale draft update accepted';
  doc:=public.quality_api('quality',null,test_password,'get',jsonb_build_object('review_id',review_id));
  perform public.quality_api('quality',null,test_password,'publish',jsonb_build_object('review_id',review_id,'updated_at',doc->>'updated_at','items',good_items));
  doc:=public.quality_api('supervisor',team_a,test_password,'get',jsonb_build_object('review_id',review_id));
  assert doc->>'status'='sent', 'publication failed';
  assert jsonb_array_length(doc->'items')=1, 'finding lost';
  item:=doc->'items'->0;
  denied:=false;
  begin perform public.quality_api('supervisor',team_b,test_password,'get',jsonb_build_object('review_id',review_id));
    exception when insufficient_privilege then denied:=true; end;
  assert denied, 'cross-team review visible';
  denied:=false;
  begin perform public.quality_api('supervisor',team_a,test_password,'close',jsonb_build_object('review_id',review_id,'finding_id',item->>'id','updated_at',item->>'updated_at'));
    exception when insufficient_privilege then denied:=true; end;
  assert denied, 'supervisor closed finding';
  denied:=false;
  begin perform public.quality_api('quality',null,test_password,'respond',jsonb_build_object('review_id',review_id,'finding_id',item->>'id','updated_at',item->>'updated_at','reply','invalid'));
    exception when insufficient_privilege then denied:=true; end;
  assert denied, 'reviewer replied as supervisor';
  perform public.quality_api('supervisor',team_a,test_password,'respond',jsonb_build_object('review_id',review_id,'finding_id',item->>'id','updated_at',item->>'updated_at','reply','تم التصحيح'));
  doc:=public.quality_api('quality',null,test_password,'get',jsonb_build_object('review_id',review_id));
  item:=doc->'items'->0;
  assert item->>'status'='resolved', 'response failed';
  perform public.quality_api('quality',null,test_password,'close',jsonb_build_object('review_id',review_id,'finding_id',item->>'id','updated_at',item->>'updated_at'));
  doc:=public.quality_api('quality',null,test_password,'get',jsonb_build_object('review_id',review_id));
  item:=doc->'items'->0;
  assert item->>'status'='closed', 'closure failed';
  perform public.quality_api('quality',null,test_password,'reopen',jsonb_build_object('review_id',review_id,'finding_id',item->>'id','updated_at',item->>'updated_at'));
  doc:=public.quality_api('quality',null,test_password,'get',jsonb_build_object('review_id',review_id));
  assert doc->'items'->0->>'status'='open', 'reopen failed';
end;
$$;
rollback;
select 'Quality workflow and access tests passed' as result;
